func generatedCheck(root string, out io.Writer) error {
	tools := [][]string{{"templ", "generate"}}
	if hasQueries(root) {
		tools = append(tools, []string{"sqlc", "generate"})
	}
	for _, tool := range tools {
		if _, err := lookPath(tool[0]); err != nil {
			return fmt.Errorf("%s isn't installed (or isn't on PATH): check --generated runs the app's generators here, the versions its Dockerfile's toolchain installs", tool[0])
		}
	}
	scratch, err := os.MkdirTemp("", "gantry-generated-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(scratch)
	generated, err := copyApp(root, scratch)
	if err != nil {
		return err
	}
	for _, tool := range tools {
		if output, err := runQuietlyIn(scratch, tool[0], tool[1:]...); err != nil {
			_, _ = out.Write(output)
			return fmt.Errorf("%s failed in a copy of the app (%v)", strings.Join(tool, " "), err)
		}
	}
	var stale []string
	err = filepath.WalkDir(scratch, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		r, _ := filepath.Rel(scratch, p)
		rel := filepath.ToSlash(r)
		made, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		g, ok := parseGenerated(rel, made)
		if !ok {
			return nil
		}
		have, there := generated[rel]
		delete(generated, rel)
		if there && bytes.Equal(have, made) {
			return nil
		}
		was, _ := parseGenerated(rel, have)
		switch {
		case !there:
			stale = append(stale, fmt.Sprintf("%s is missing: %s makes it from %s; run bin/gantry exec %s and commit it", rel, g.tool, g.source, g.tool))
		case was.version != "" && was.version != g.version:
			stale = append(stale, fmt.Sprintf("%s was made by %s %s, and the %s here is %s: check with the app's, the version its Dockerfile installs", rel, g.name, was.version, g.name, g.version))
		default:
			stale = append(stale, fmt.Sprintf("%s differs from %s of %s; edit %s, not the generated file, and run bin/gantry exec %s (it replaces generated files)", rel, g.tool, g.source, g.edit, g.tool))
		}
		return nil
	})
	if err != nil {
		return err
	}
	for rel, have := range generated {
		g, _ := parseGenerated(rel, have)
		stale = append(stale, fmt.Sprintf("%s isn't made by %s any more: delete it, or restore %s", rel, g.tool, g.source))
	}
	sort.Strings(stale)
	for _, s := range stale {
		fmt.Fprintln(out, s)
	}
	fmt.Fprintf(out, "gantry check --generated: %d stale generated file(s)\n", len(stale))
	if len(stale) > 0 {
		return errExit(1)
	}
	return nil
}

type generatedFile struct {
	name    string
	tool    string
	source  string
	edit    string
	version string
}

var (
	templHeader = regexp.MustCompile(`\A// Code generated by templ\b`)
	sqlcHeader  = regexp.MustCompile(`\A// Code generated by sqlc\b`)
	templStamp  = regexp.MustCompile(`(?m)^// templ: version: (\S+)$`)
	sqlcStamp   = regexp.MustCompile(`(?m)^//\s+sqlc (v\S+)$`)
	sqlcSource  = regexp.MustCompile(`(?m)^// source: (\S+)$`)
)

func parseGenerated(rel string, body []byte) (g generatedFile, ok bool) {
	switch {
	case strings.HasSuffix(rel, "_templ.go") || templHeader.Match(body):
		g = generatedFile{name: "templ", tool: "templ generate", source: strings.TrimSuffix(rel, "_templ.go") + ".templ"}
		g.edit = g.source
		if m := templStamp.FindSubmatch(body); m != nil {
			g.version = string(m[1])
		}
	case strings.HasSuffix(rel, ".go") && sqlcHeader.Match(body):
		g = generatedFile{name: "sqlc", tool: "sqlc generate", source: "db/schema.sql and sqlc.yaml", edit: "a migration (bin/gantry db migrate writes db/schema.sql) or sqlc.yaml"}
		if m := sqlcSource.FindSubmatch(body); m != nil {
			g.source = path.Join(path.Dir(rel), string(m[1]))
			g.edit = g.source
		}
		if m := sqlcStamp.FindSubmatch(body); m != nil {
			g.version = string(m[1])
		}
	default:
		return g, false
	}
	return g, true
}

func hasQueries(root string) bool {
	data, err := os.ReadFile(filepath.Join(root, "sqlc.yaml"))
	if err != nil {
		return false
	}
	for _, line := range strings.Split(string(data), "\n") {
		v, ok := strings.CutPrefix(strings.TrimLeft(strings.TrimSpace(line), "- "), "queries:")
		if !ok {
			continue
		}
		pattern := filepath.Join(root, filepath.FromSlash(strings.Trim(strings.TrimSpace(v), `"'`)))
		if info, err := os.Stat(pattern); err == nil && info.IsDir() {
			pattern = filepath.Join(pattern, "*.sql")
		}
		if found, _ := filepath.Glob(pattern); len(found) > 0 {
			return true
		}
	}
	return false
}

func copyApp(root, dir string) (generated map[string][]byte, err error) {
	generated = map[string][]byte{}
	err = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, p)
		if d.IsDir() {
			switch filepath.ToSlash(rel) {
			case ".git", ".gantry", ".cache", "node_modules", "assets/built":
				return filepath.SkipDir
			}
			return os.MkdirAll(filepath.Join(dir, rel), 0o755)
		}
		if !d.Type().IsRegular() {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if _, ok := parseGenerated(filepath.ToSlash(rel), b); ok {
			generated[filepath.ToSlash(rel)] = b
			return nil
		}
		return os.WriteFile(filepath.Join(dir, rel), b, 0o644)
	})
	return generated, err
}
