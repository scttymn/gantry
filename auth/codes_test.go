type codeMail struct {
	mu   sync.Mutex
	sent []mail.Message
	fail bool
}

func (m *codeMail) Send(_ context.Context, msg mail.Message) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.fail {
		return errors.New("delivery unavailable")
	}
	m.sent = append(m.sent, msg)
	return nil
}

func (m *codeMail) code(t *testing.T) string {
	t.Helper()
	m.mu.Lock()
	defer m.mu.Unlock()
	if len(m.sent) == 0 {
		t.Fatal("no email")
	}
	code := regexp.MustCompile(`\b[0-9]{6}\b`).FindString(m.sent[len(m.sent)-1].Text)
	if code == "" {
		t.Fatal("no six-digit code")
	}
	return code
}

func newCodeApp(t *testing.T, engine string) (*Auth, *codeMail, *time.Time) {
	t.Helper()
	ddl := `CREATE TABLE users (id integer PRIMARY KEY, email_address text NOT NULL UNIQUE, password_digest text NOT NULL, created_at datetime NOT NULL, updated_at datetime NOT NULL);
CREATE TABLE sessions (id integer PRIMARY KEY, user_id integer NOT NULL REFERENCES users(id), token_digest text NOT NULL UNIQUE, ip_address text NOT NULL, user_agent text NOT NULL, created_at datetime NOT NULL, last_seen_at datetime NOT NULL);`
	if engine == "postgres" {
		ddl = strings.ReplaceAll(ddl, "integer PRIMARY KEY", "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
		ddl = strings.ReplaceAll(ddl, "datetime", "timestamptz")
	}
	ddl += `
CREATE TABLE auth_login_codes (challenge_digest text PRIMARY KEY, email_address text NOT NULL UNIQUE, code_digest text NOT NULL, expires_at bigint NOT NULL, attempts integer NOT NULL DEFAULT 0);
CREATE INDEX auth_login_codes_expiry ON auth_login_codes(expires_at);
CREATE TABLE auth_code_limits (bucket text PRIMARY KEY, count integer NOT NULL, expires_at bigint NOT NULL);
CREATE INDEX auth_code_limits_expiry ON auth_code_limits(expires_at);`
	migrate := func(ctx context.Context, d *db.DB) error {
		return d.Migrate(ctx, fstest.MapFS{"00001_auth.sql": {Data: []byte("-- +goose Up\n" + ddl)}}, "app_migrations")
	}
	var d *db.DB
	if engine == "postgres" {
		server := os.Getenv("GANTRY_TEST_POSTGRES_URL")
		if server == "" {
			t.Skip("GANTRY_TEST_POSTGRES_URL not set")
		}
		t.Setenv("TEST_DATABASE_URL", server)
		d = testkit.Postgres(t, migrate)
	} else {
		d = testkit.DB(t, migrate)
	}
	now := time.Date(2026, 10, 12, 12, 0, 0, 0, time.UTC)
	m := &codeMail{}
	a := &Auth{DB: d, Mail: m, From: "Test <login@example.com>", Signer: sign.Signer{Key: []byte("cookie key")},
		EmailCodes: &EmailCodes{Key: []byte(strings.Repeat("k", 32)), Signup: true},
		Now:        func() time.Time { return now }, Log: slog.New(slog.DiscardHandler)}
	return a, m, &now
}

func TestEmailCodes(t *testing.T) {
	for _, engine := range []string{"sqlite", "postgres"} {
		t.Run(engine, func(t *testing.T) {
			t.Run("signup happens only after proof and existing users return", func(t *testing.T) {
				a, m, now := newCodeApp(t, engine)
				challenge, err := a.RequestLoginCode(t.Context(), " NEW@Example.com ", "ip")
				if err != nil {
					t.Fatal(err)
				}
				if _, err := a.FindByEmail(t.Context(), "new@example.com"); !errors.Is(err, ErrNoUser) {
					t.Fatalf("premature user: %v", err)
				}
				code := m.code(t)
				var stored string
				if err := a.DB.Read.QueryRow(`SELECT code_digest FROM auth_login_codes`).Scan(&stored); err != nil {
					t.Fatal(err)
				}
				if stored == code || len(stored) != 64 {
					t.Fatal("plaintext code stored")
				}
				u, err := a.VerifyLoginCode(t.Context(), challenge, code, "ip")
				if err != nil || u.EmailAddress != "new@example.com" || u.PasswordDigest != "" {
					t.Fatalf("signup: %+v %v", u, err)
				}
				if _, ok := a.Authenticate(t.Context(), u.EmailAddress, ""); ok {
					t.Fatal("passwordless account accepted an empty password")
				}
				if _, err := a.VerifyLoginCode(t.Context(), challenge, code, "ip"); !errors.Is(err, ErrBadCode) {
					t.Fatalf("replay: %v", err)
				}
				*now = now.Add(time.Minute)
				challenge, err = a.RequestLoginCode(t.Context(), u.EmailAddress, "ip")
				if err != nil {
					t.Fatal(err)
				}
				again, err := a.VerifyLoginCode(t.Context(), challenge, m.code(t), "ip")
				if err != nil || again.ID != u.ID {
					t.Fatalf("existing account: %+v %v", again, err)
				}
			})
			t.Run("signup is opt in and unknown requests look alike", func(t *testing.T) {
				a, m, _ := newCodeApp(t, engine)
				a.EmailCodes.Signup = false
				c, err := a.RequestLoginCode(t.Context(), "unknown@example.com", "ip")
				if err != nil {
					t.Fatal(err)
				}
				if _, err := a.VerifyLoginCode(t.Context(), c, m.code(t), "ip"); !errors.Is(err, ErrBadCode) {
					t.Fatalf("unknown signup: %v", err)
				}
				if _, err := a.FindByEmail(t.Context(), "unknown@example.com"); !errors.Is(err, ErrNoUser) {
					t.Fatal("unknown user created")
				}
			})
			t.Run("expiry replacement wrong codes and attempt cap", func(t *testing.T) {
				a, m, now := newCodeApp(t, engine)
				old, _ := a.RequestLoginCode(t.Context(), "one@example.com", "ip")
				oldCode := m.code(t)
				*now = now.Add(time.Minute)
				c, err := a.RequestLoginCode(t.Context(), "one@example.com", "ip")
				if err != nil {
					t.Fatal(err)
				}
				code := m.code(t)
				if _, err := a.VerifyLoginCode(t.Context(), old, oldCode, "ip"); !errors.Is(err, ErrBadCode) {
					t.Fatalf("replaced code: %v", err)
				}
				for range 5 {
					if _, err := a.VerifyLoginCode(t.Context(), c, "wrong", "ip"); !errors.Is(err, ErrBadCode) {
						t.Fatalf("wrong code: %v", err)
					}
				}
				if _, err := a.VerifyLoginCode(t.Context(), c, code, "ip"); !errors.Is(err, ErrBadCode) {
					t.Fatalf("exhausted code: %v", err)
				}
				*now = now.Add(15 * time.Minute)
				c, err = a.RequestLoginCode(t.Context(), "one@example.com", "ip")
				if err != nil {
					t.Fatal(err)
				}
				*now = now.Add(10 * time.Minute)
				if _, err := a.VerifyLoginCode(t.Context(), c, m.code(t), "ip"); !errors.Is(err, ErrBadCode) {
					t.Fatalf("expired: %v", err)
				}
			})
			t.Run("limits survive a new Auth instance and email casing", func(t *testing.T) {
				a, _, now := newCodeApp(t, engine)
				if _, err := a.RequestLoginCode(t.Context(), "one@example.com", "ip"); err != nil {
					t.Fatal(err)
				}
				other := *a
				if _, err := other.RequestLoginCode(t.Context(), " ONE@EXAMPLE.COM ", "other-ip"); !errors.Is(err, ErrCodeLimited) {
					t.Fatalf("cooldown: %v", err)
				}
				for range 2 {
					*now = now.Add(time.Minute)
					if _, err := a.RequestLoginCode(t.Context(), "one@example.com", "ip"); err != nil {
						t.Fatal(err)
					}
				}
				*now = now.Add(time.Minute)
				if _, err := other.RequestLoginCode(t.Context(), "one@example.com", "different-ip"); !errors.Is(err, ErrCodeLimited) {
					t.Fatalf("email limit: %v", err)
				}
			})
			t.Run("IP daily and verification limits", func(t *testing.T) {
				a, _, now := newCodeApp(t, engine)
				for i := range 20 {
					if _, err := a.RequestLoginCode(t.Context(), string(rune('a'+i))+"@example.com", "same-ip"); err != nil {
						t.Fatal(err)
					}
				}
				if _, err := a.RequestLoginCode(t.Context(), "overflow@example.com", "same-ip"); !errors.Is(err, ErrCodeLimited) {
					t.Fatalf("IP limit: %v", err)
				}
				for range 50 {
					a.VerifyLoginCode(t.Context(), "bogus", "123456", "verify-ip")
				}
				if _, err := a.VerifyLoginCode(t.Context(), "bogus", "123456", "verify-ip"); !errors.Is(err, ErrCodeLimited) {
					t.Fatalf("verification limit: %v", err)
				}
				*now = now.Add(15 * time.Minute)
				a.EmailCodes.DailyLimit = 1
				if _, err := a.RequestLoginCode(t.Context(), "daily@example.com", "new-ip"); err != nil {
					t.Fatal(err)
				}
				if _, err := a.RequestLoginCode(t.Context(), "daily2@example.com", "newer-ip"); !errors.Is(err, ErrCodeLimited) {
					t.Fatalf("daily limit: %v", err)
				}
			})
			t.Run("only one concurrent verification succeeds", func(t *testing.T) {
				a, m, _ := newCodeApp(t, engine)
				c, err := a.RequestLoginCode(t.Context(), "race@example.com", "ip")
				if err != nil {
					t.Fatal(err)
				}
				code := m.code(t)
				var wg sync.WaitGroup
				var successes atomic.Int32
				for range 12 {
					wg.Go(func() {
						other := *a
						if _, err := other.VerifyLoginCode(t.Context(), c, code, "ip"); err == nil {
							successes.Add(1)
						} else if !errors.Is(err, ErrBadCode) {
							t.Errorf("verify: %v", err)
						}
					})
				}
				wg.Wait()
				if successes.Load() != 1 {
					t.Fatalf("successes: %d", successes.Load())
				}
			})
			t.Run("concurrent wrong attempts never exceed five", func(t *testing.T) {
				a, m, _ := newCodeApp(t, engine)
				c, _ := a.RequestLoginCode(t.Context(), "guess@example.com", "ip")
				code := m.code(t)
				var wg sync.WaitGroup
				for range 12 {
					wg.Go(func() { a.VerifyLoginCode(t.Context(), c, "wrong", "ip") })
				}
				wg.Wait()
				var attempts int
				if err := a.DB.Read.QueryRow(`SELECT attempts FROM auth_login_codes`).Scan(&attempts); err != nil || attempts != 5 {
					t.Fatalf("attempts: %d %v", attempts, err)
				}
				if _, err := a.VerifyLoginCode(t.Context(), c, code, "other-ip"); !errors.Is(err, ErrBadCode) {
					t.Fatalf("exhausted: %v", err)
				}
			})
			t.Run("delivery failures invalidate the challenge", func(t *testing.T) {
				a, m, _ := newCodeApp(t, engine)
				m.fail = true
				if _, err := a.RequestLoginCode(t.Context(), "fail@example.com", "ip"); !errors.Is(err, ErrCodeDelivery) {
					t.Fatalf("send: %v", err)
				}
				var n int
				a.DB.Read.QueryRow(`SELECT COUNT(*) FROM auth_login_codes`).Scan(&n)
				if n != 0 {
					t.Fatal("failed delivery left a live code")
				}
			})
			t.Run("signup failure rolls back consumption", func(t *testing.T) {
				a, m, _ := newCodeApp(t, engine)
				a.EmailCodes.CreateUser = func(context.Context, *db.Tx, string) (User, error) { return User{}, errors.New("signup failed") }
				c, _ := a.RequestLoginCode(t.Context(), "custom@example.com", "ip")
				code := m.code(t)
				if _, err := a.VerifyLoginCode(t.Context(), c, code, "ip"); err == nil {
					t.Fatal("signup failure ignored")
				}
				a.EmailCodes.CreateUser = nil
				if _, err := a.VerifyLoginCode(t.Context(), c, code, "ip"); err != nil {
					t.Fatalf("rolled-back code lost: %v", err)
				}
			})
			t.Run("secret rotation and pruning", func(t *testing.T) {
				a, m, now := newCodeApp(t, engine)
				c, _ := a.RequestLoginCode(t.Context(), "rotate@example.com", "ip")
				a.EmailCodes.Key = []byte(strings.Repeat("z", 32))
				if _, err := a.VerifyLoginCode(t.Context(), c, m.code(t), "ip"); !errors.Is(err, ErrBadCode) {
					t.Fatal("code survived key rotation")
				}
				*now = now.Add(24 * time.Hour)
				if err := a.PruneLoginCodes(t.Context()); err != nil {
					t.Fatal(err)
				}
				for _, table := range []string{"auth_login_codes", "auth_code_limits"} {
					var n int
					a.DB.Read.QueryRow(`SELECT COUNT(*) FROM ` + table).Scan(&n)
					if n != 0 {
						t.Errorf("%s not pruned", table)
					}
				}
			})
		})
	}
}

func TestEmailCodeRoutes(t *testing.T) {
	a, m, _ := newCodeApp(t, "sqlite")
	a.Paths = Paths{Login: "/sign-in", AfterLogin: "/account"}
	rt := web.NewRouter(slog.New(slog.DiscardHandler), nil)
	a.Routes(rt)
	rt.Mount("GET /account", a.Require(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { u, _ := Current(r); io.WriteString(w, u.EmailAddress) })))
	browser := &app{t: t, auth: a, h: rt.Handler()}
	if body := browser.do("GET", "/sign-in", nil).Body.String(); strings.Contains(body, `name="password"`) || !strings.Contains(body, `name="email_address"`) {
		t.Fatalf("email form: %s", body)
	}
	if rec := browser.do("GET", "/passwords/new", nil); rec.Code != 404 {
		t.Fatal("password reset mounted in code mode")
	}
	if rec := browser.do("POST", "/sign-in", url.Values{"email_address": {" NEW@example.com "}}); rec.Code != 303 || rec.Header().Get("Location") != "/sign-in/verify" {
		t.Fatalf("request: %d %v", rec.Code, rec.Header())
	}
	if body := browser.do("GET", "/sign-in/verify", nil).Body.String(); !strings.Contains(body, `autocomplete="one-time-code"`) || !strings.Contains(body, "new@example.com") {
		t.Fatalf("verify form: %s", body)
	}
	if rec := browser.do("POST", "/sign-in/verify", url.Values{"code": {m.code(t)}}); rec.Code != 303 || rec.Header().Get("Location") != "/account" {
		t.Fatalf("verify: %d %v %s", rec.Code, rec.Header(), rec.Body)
	}
	if browser.cookie("session") == nil || browser.cookie("login_code") != nil {
		t.Fatal("session/challenge cookies incorrect")
	}
	if got := browser.do("GET", "/account", nil).Body.String(); got != "new@example.com" {
		t.Fatalf("account: %s", got)
	}
	if rec := browser.do("POST", "/logout", nil); rec.Code != 303 || browser.cookie("session") != nil {
		t.Fatal("sign-out failed")
	}
}

