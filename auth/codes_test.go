// independentAuth opens a second connection pool to the same data. In
// particular SQLite must rely on its database locks, not one pool's mutex.
func independentAuth(t *testing.T, a *Auth) *Auth {
	t.Helper()
	other := *a
	var address string
	if a.DB.Engine == db.SQLite {
		var seq int
		var name, filename string
		if err := a.DB.Read.QueryRow(`PRAGMA database_list`).Scan(&seq, &name, &filename); err != nil {
			t.Fatal(err)
		}
		address = "sqlite://" + filename
	} else {
		u, err := url.Parse(os.Getenv("GANTRY_TEST_POSTGRES_URL"))
		if err != nil {
			t.Fatal(err)
		}
		var database string
		if err := a.DB.Read.QueryRow(`SELECT current_database()`).Scan(&database); err != nil {
			t.Fatal(err)
		}
		u.Path = "/" + database
		address = u.String()
	}
	d, err := db.Open(t.Context(), address)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { d.Close() })
	other.DB = d
	return &other
}

func TestEmailCodesAcrossInstances(t *testing.T) {
	for _, engine := range []string{"sqlite", "postgres"} {
		t.Run(engine, func(t *testing.T) {
			a, m, _ := newCodeApp(t, engine)
			b := independentAuth(t, a)
			var wg sync.WaitGroup
			var successes atomic.Int32
			var challenge string
			var mu sync.Mutex
			for i := range 8 {
				client := a
				if i%2 == 0 {
					client = b
				}
				wg.Go(func() {
					c, err := client.RequestLoginCode(t.Context(), "parallel@example.com", string(rune('a'+i)))
					if err == nil {
						successes.Add(1)
						mu.Lock()
						challenge = c
						mu.Unlock()
					} else if !errors.Is(err, ErrCodeLimited) {
						t.Errorf("send: %v", err)
					}
				})
			}
			wg.Wait()
			if successes.Load() != 1 {
				t.Fatalf("parallel sends: %d", successes.Load())
			}
			code := m.code(t)
			successes.Store(0)
			for i := range 8 {
				client := a
				if i%2 == 0 {
					client = b
				}
				wg.Go(func() {
					if _, err := client.VerifyLoginCode(t.Context(), challenge, code, string(rune('a'+i))); err == nil {
						successes.Add(1)
					} else if !errors.Is(err, ErrBadCode) {
						t.Errorf("verify: %v", err)
					}
				})
			}
			wg.Wait()
			if successes.Load() != 1 {
				t.Fatalf("parallel verifications: %d", successes.Load())
			}
		})
	}
}

func TestEmailCodeBrowserGuards(t *testing.T) {
	a, m, _ := newCodeApp(t, "sqlite")
	rt := web.NewRouter(slog.New(slog.DiscardHandler), nil)
	a.Routes(rt)
	rt.Mount("GET /private", a.Require(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {})))
	browser := &app{t: t, auth: a, h: rt.Handler()}
	if rec := browser.do("GET", "/login/verify", nil); rec.Code != 303 || rec.Header().Get("Location") != "/login" {
		t.Fatal("verify needs a challenge")
	}
	r := httptest.NewRequest("POST", "https://example.com/login", strings.NewReader("email_address=cross%40example.com"))
	r.Header.Set("Content-Type", "application/x-www-form-urlencoded")
	r.Header.Set("Sec-Fetch-Site", "cross-site")
	w := httptest.NewRecorder()
	browser.h.ServeHTTP(w, r)
	if w.Code != http.StatusUnprocessableEntity || len(m.sent) != 0 {
		t.Fatalf("cross-site send: status=%d, emails=%d", w.Code, len(m.sent))
	}
	browser.do("GET", "/private", nil)
	browser.do("POST", "/login", url.Values{"email_address": {"rider@example.com"}})
	if cookie := browser.cookie(codeCookie); cookie == nil || !cookie.HttpOnly || !cookie.Secure {
		t.Fatal("challenge cookie isn't protected")
	}
	if rec := browser.do("POST", "/login", url.Values{"email_address": {"rider@example.com"}}); rec.Header().Get("Location") != "/login/verify" || len(m.sent) != 1 {
		t.Fatal("limited resend should preserve the existing verification flow")
	}
	var failed string
	a.Failed = func(_ *http.Request, email string) { failed = email }
	browser.do("POST", "/login/verify", url.Values{"code": {"wrong"}})
	if failed != "rider@example.com" {
		t.Fatal("failed hook missing")
	}
	a.Attempt = func(*http.Request) bool { return false }
	browser.do("POST", "/login/verify", url.Values{"code": {m.code(t)}})
	if browser.cookie("session") != nil {
		t.Fatal("attempt hook ignored")
	}
	a.Attempt = nil
	if rec := browser.do("POST", "/login/verify", url.Values{"code": {m.code(t)}}); rec.Header().Get("Location") != "/private" {
		t.Fatal("return-to lost")
	}

	a2, m2, _ := newCodeApp(t, "sqlite")
	rt2 := web.NewRouter(slog.New(slog.DiscardHandler), nil)
	a2.Routes(rt2)
	b2 := &app{t: t, auth: a2, h: rt2.Handler()}
	b2.do("POST", "/login", url.Values{"email_address": {"rider@example.com"}})
	b2.cookie(codeCookie).Value += "tampered"
	b2.do("POST", "/login/verify", url.Values{"code": {m2.code(t)}})
	if b2.cookie("session") != nil {
		t.Fatal("tampered challenge accepted")
	}
}
