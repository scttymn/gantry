func TestCommentsTakeNoExceptions(t *testing.T) {
	root := t.TempDir()
	put(t, root, "go.mod", "module example.com/shop\n")
	put(t, root, "app/routes.go", "package app\n\n// routes\nfunc routes() {}\n")
	put(t, root, ".gantry-check.json", `{"requireIssue":true,"exceptions":[{"rule":"comments","file":"app/routes.go","reason":"Explains the routes (#61)."}]}`)
	_, err := Scan(root)
	if err == nil || err.Error() != ".gantry-check.json: exception comments app/routes.go: comments takes no exceptions; fix what it finds instead" {
		t.Fatal(err)
	}
}
