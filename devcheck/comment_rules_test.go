func commentFindings(t *testing.T, module string, files map[string]string) []string {
	t.Helper()
	root := t.TempDir()
	put(t, root, "go.mod", "module "+module+"\n\ngo 1.27\n")
	for name, body := range files {
		put(t, root, name, body)
	}
	warnings, err := Scan(root)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, w := range warnings {
		if w.Rule == "comments" {
			if w.Severity != Violation {
				t.Errorf("%+v: want a violation", w)
			}
			got = append(got, fmt.Sprintf("%s:%d %s", w.File, w.Line, w.Message))
		}
	}
	return got
}

